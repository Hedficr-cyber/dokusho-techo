const byName = new Map(Object.entries(readings).map(([name, reading]) => [normName(name), reading]));
const collator = new Intl.Collator('ja', { sensitivity:'base', numeric:true });
export function authorReading(book) {
  const name = book.author || '';
  const known = (book.authorReading || '').trim() || byName.get(normName(name));
  if (known) return known;
  return /[\p{Script=Han}]/u.test(name) ? '' : name;
}
export function readingKey(reading) {
  return reading.normalize('NFKC').replace(/^Dr\.\s*/i,'ドクター').replace(/^M[・\s]*W[・\s]*/i,'エムダブリュー')
    .replace(/[ァ-ヶ]/g,c=>String.fromCharCode(c.charCodeAt(0)-0x60)).replace(/[\s,、・.]/g,'');
}
export function compareAuthors(a,b) {
  const ar=readingKey(authorReading(a)),br=readingKey(authorReading(b));
  if (!ar || !br) { if (!!ar!==!!br) return ar ? -1 : 1; }
  return collator.compare(ar,br) || collator.compare(a.author || '',b.author || '');
}
