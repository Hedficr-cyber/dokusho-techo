export const GENRE_BY_ID = Object.fromEntries(GENRES.map((g) => [g.id,g]));
export function belongsToGenre(book, id) {
  const group=GENRE_GROUP_BY_ID[id];
  const ids=group ? [...group.children,...(group.traits || [])] : [id];
  return ids.some((g) => book.genres?.includes(g));
}

